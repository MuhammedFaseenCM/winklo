/// Members that are deliberately the same in every language: the game names
/// and "Winklo", symbols, and formats made of numbers.
const _sameInEveryLanguage = {
  'appTitle',
  'zipTitle',
  'pathWordsTitle',
  'sudokuTitle',
  'pathWordsTab',
  'zipBrand',
  'statsNoValue',
  'statsPercent',
  'statsTimesBucket',
  'leaderboardGapEllipsis',
  'leagueCodeHint',
  'freezeCountLabel',
  'widgetCleared',
  'widgetStreak',
  'updateVersionRow',
  'bonusRunLabel',
  'bonusSecondsLeft',
  'languageEnglish',
  'languageMalayalam',
};

final _malayalamScript = RegExp('[\u0D00-\u0D7F]');

void main() {
  const en = AppTextEn();
  const ml = AppTextMl();

  test('the sample table covers every AppText member', () {
    final source = File('lib/core/strings/app_text.dart').readAsStringSync();
    final declared = RegExp(
      r'^  String (?:get )?(\w+)',
      multiLine: true,
    ).allMatches(source).map((m) => m.group(1)).toSet();
    expect(_members.keys.toSet(), declared);
  });

  test('every member is non-empty in both tables', () {
    for (final MapEntry(:key, :value) in _members.entries) {
      expect(value(en).trim(), isNotEmpty, reason: 'en $key');
      expect(value(ml).trim(), isNotEmpty, reason: 'ml $key');
    }
  });

  test('Malayalam differs from English, except the allowlist', () {
    for (final MapEntry(:key, :value) in _members.entries) {
      if (_sameInEveryLanguage.contains(key)) {
        expect(value(ml), value(en), reason: key);
      } else {
        expect(value(ml), isNot(value(en)), reason: key);
        expect(value(ml), contains(_malayalamScript), reason: key);
      }
    }
  });
}
